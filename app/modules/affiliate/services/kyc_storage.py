from __future__ import annotations

import hashlib
import os
from pathlib import Path
from uuid import uuid4


MAX_KYC_FILE_SIZE = 5 * 1024 * 1024  # 5 MB

ALLOWED_DOCUMENTS = {
    "AADHAAR_FRONT",
    "AADHAAR_BACK",
    "PAN_CARD",
}

ALLOWED_CONTENT_TYPES = {
    "application/pdf",
    "image/jpeg",
    "image/png",
}


class KYCStorageError(Exception):
    pass


def detect_file_type(data: bytes) -> str:
    """Detect basic PDF, JPEG, and PNG signatures."""

    if data.startswith(b"%PDF-"):
        return "application/pdf"

    if data.startswith(b"\xff\xd8\xff"):
        return "image/jpeg"

    if data.startswith(b"\x89PNG\r\n\x1a\n"):
        return "image/png"

    raise KYCStorageError(
        "Unsupported or invalid file content. Upload a valid PDF, JPEG, or PNG."
    )


class LocalDevelopmentKYCStorage:
    """
    Development-only private filesystem storage.

    This is not a production storage adapter.
    """

    def __init__(self) -> None:
        environment = os.getenv("APP_ENV", "development").lower()

        if environment in {"production", "prod"}:
            raise KYCStorageError(
                "Local KYC storage is disabled in production. "
                "Configure a private object-storage adapter."
            )

        configured_path = os.getenv(
            "KYC_LOCAL_STORAGE_DIR",
            ".private_kyc_storage",
        )

        self.root = Path(configured_path).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def save(self, data: bytes) -> str:
        if not data:
            raise KYCStorageError("The uploaded file is empty.")

        if len(data) > MAX_KYC_FILE_SIZE:
            raise KYCStorageError("The file exceeds the 5 MB limit.")

        storage_key = f"{uuid4().hex}.bin"
        destination = self.root / storage_key

        # Exclusive creation prevents accidental overwrites.
        with destination.open("xb") as file:
            file.write(data)

        return storage_key

    def read(self, storage_key: str) -> bytes:
        # Storage keys must be generated by the server.
        if (
            not storage_key
            or "/" in storage_key
            or "\\" in storage_key
            or storage_key in {".", ".."}
        ):
            raise KYCStorageError("Invalid storage key.")

        destination = (self.root / storage_key).resolve()

        if destination.parent != self.root:
            raise KYCStorageError("Invalid storage path.")

        if not destination.is_file():
            raise KYCStorageError("Document not found.")

        return destination.read_bytes()

    def delete(self, storage_key: str) -> None:
        if (
            not storage_key
            or "/" in storage_key
            or "\\" in storage_key
            or storage_key in {".", ".."}
        ):
            raise KYCStorageError("Invalid storage key.")

        destination = (self.root / storage_key).resolve()

        if destination.parent != self.root:
            raise KYCStorageError("Invalid storage path.")

        destination.unlink(missing_ok=True)


def calculate_sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()